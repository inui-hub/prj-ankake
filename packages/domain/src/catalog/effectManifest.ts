export const CANONICAL_EFFECT_MANIFEST: EffectManifest = CANONICAL_EFFECT_TEXTS.trim().split("\n").map((row) => {
  const [cardId, text] = row.split("|", 2);
  if (text === "なし") return { cardId, textDigest: effectTextDigest(text), effects: "none" };
  const definition: EffectDefinition = {
    effectId: `${cardId}.primary`, trigger: triggerFor(text), target: "documented",
    operations: [{ kind: "documented", text }]
  };
  return { cardId, textDigest: effectTextDigest(text), effects: [definition] };
});

function triggerFor(text: string): EffectTrigger {
  if (text.startsWith("召喚時")) return "summon";
  if (text.startsWith("破壊時")) return "destroyed";
  if (text.includes("場にいる限り") || text.includes("このクリーチャーは")) return "continuous";
  return text.includes("なら") || text.includes("とき") ? "conditional" : "play";
}
